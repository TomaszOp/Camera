/**
 * @file CameraPins.h
 * @brief GPIO assignment of the camera module. Defaults to ESP32-CAM AI Thinker (OV2640).
 */
#pragma once

namespace espcamweb {

/**
 * @brief GPIO numbers of the camera sensor interface (DVP data bus, sync lines, SCCB, control).
 *
 * Use -1 for a signal that is not connected (e.g. @c reset on AI Thinker).
 * Fill in a custom instance for other camera modules and assign it to CameraSettings::pins.
 */
struct CameraPins {
  int pwdn;   ///< Power-down pin (active high).
  int reset;  ///< Reset pin, -1 if not connected.
  int xclk;   ///< Master clock output to the sensor (generated by LEDC).
  int sda;    ///< SCCB (I2C-like) data line, a.k.a. SIOD.
  int scl;    ///< SCCB clock line, a.k.a. SIOC.
  int d0, d1, d2, d3, d4, d5, d6, d7;  ///< Parallel data bus, D0..D7 = Y2..Y9.
  int vsync;  ///< Vertical sync.
  int href;   ///< Horizontal reference.
  int pclk;   ///< Pixel clock.
};

/// Camera pin map of the ESP32-CAM AI Thinker board.
inline constexpr CameraPins AI_THINKER_PINS = {
    /*pwdn*/ 32, /*reset*/ -1, /*xclk*/ 0, /*sda*/ 26, /*scl*/ 27,
    /*d0..d7*/ 5, 18, 19, 21, 36, 39, 34, 35,
    /*vsync*/ 25, /*href*/ 23, /*pclk*/ 22,
};

/// Flash LED pin on the ESP32-CAM AI Thinker board.
inline constexpr int AI_THINKER_LED_PIN = 4;

}  // namespace espcamweb
